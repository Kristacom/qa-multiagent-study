def p(text: str, bold: bool = False):
    c = {"type": "text", "text": text}
    if bold:
        c["marks"] = [{"type": "strong"}]
    return {"type": "paragraph", "content": [c]}


def h(text: str, level: int = 2):
    return {
        "type": "heading",
        "attrs": {"level": level},
        "content": [{"type": "text", "text": text}],
    }


def bullet_list(items):
    return {
        "type": "bulletList",
        "content": [
            {
                "type": "listItem",
                "content": [
                    {
                        "type": "paragraph",
                        "content": [{"type": "text", "text": item}],
                    }
                ],
            }
            for item in items
        ],
    }


def update_issue(key: str, adf_doc: dict):
    url = f"https://kristapro.atlassian.net/rest/api/3/issue/{key}"
    data = json.dumps({"fields": {"description": adf_doc}}).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data,
        headers={
            "Authorization": f"Basic {AUTH}",
            "Content-Type": "application/json",
        },
        method="PUT",
    )
    urllib.request.urlopen(req)
    print(f"Updated description for {key}")


